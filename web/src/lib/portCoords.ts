/** Best-effort lookup: try the raw normalized name, then a loose contains-match
 *  against the table's keys (covers cases like "port of new york" or "nhava sheva (jnpt)"). */
export function findPortCoords(name: string | null | undefined): [number, number] | null {
  if (!name) return null;
  const n = name.trim().toLowerCase();
  if (PORT_COORDS[n]) return PORT_COORDS[n];
  for (const key of Object.keys(PORT_COORDS)) {
    if (n.includes(key) || key.includes(n)) return PORT_COORDS[key];
  }
  return null;
}
